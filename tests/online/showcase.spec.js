import { test, expect } from '@playwright/test';

test('guest quick play, character search, comparisons and local portraits work', async ({ page }, info) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.locator('.hero-fighters img')).toHaveCount(3);
  await expect.poll(() => page.locator('.hero-fighters img').evaluateAll(images => images.every(image => image.complete && image.naturalWidth > 0))).toBe(true);
  await page.getByRole('link', { name: 'Play a 60-second challenge', exact: true }).click();
  await expect(page.locator('.quiz-question-title')).toBeVisible();
  await expect(page.locator('.quiz-question-title')).not.toContainText('answerIndex');
  await page.goto('/games');
  await page.getByRole('button', { name: 'Play Clue Chain', exact: true }).click();
  await expect(page.locator('.mini-question-title')).toBeVisible();
  await expect(page.locator('.choice-portrait')).toHaveCount(4);
  await expect(page.locator('.answer-fighter')).toHaveCount(0);
  await page.locator('.mini-options button').first().click();
  await expect(page.locator('.answer-fighter img')).toBeVisible();
  await page.goto('/characters');
  await page.getByRole('searchbox', { name: 'Search fighters' }).fill('kakashi');
  await expect(page.locator('.roster-tile')).toHaveCount(1);
  await page.locator('.roster-tile').click();
  await expect(page.locator('.guide-rating h3')).toHaveText('Kakashi Hatake');
  const portrait = await page.locator('.guide-rating img').getAttribute('src');
  await page.getByRole('combobox', { name: 'Form', exact: true }).selectOption({ index: 1 });
  await expect(page.locator('.guide-rating img')).toHaveAttribute('src', portrait);
  await page.getByRole('combobox', { name: 'Compare with', exact: true }).selectOption('naruto-uzumaki');
  await expect(page.locator('.dossier-comparison .guide-rating')).toHaveCount(2);
  await expect(page.locator('.comparison-note')).toContainText('Matchups');
  await page.getByRole('searchbox', { name: 'Search fighters' }).fill('zzzzzz');
  await expect(page.getByRole('status').filter({ hasText: 'No fighters found' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('character-comparison.png'), fullPage: true });
  expect(errors).toEqual([]);
});

test('broken portraits retain a readable fallback and credits record sources', async ({ page }) => {
  await page.route('**/characters/kakashi-hatake*.webp', route => route.abort());
  await page.goto('/characters');
  await page.getByRole('searchbox', { name: 'Search fighters' }).fill('kakashi');
  const tile = page.locator('.roster-tile');
  await expect(tile.locator('.avatar-monogram')).toHaveText('KH');
  await expect(tile.locator('img')).toHaveCount(0);
  await tile.click();
  await expect(page.locator('.guide-rating .avatar-monogram')).toHaveText('KH');
  await page.goto('/credits');
  await expect(page.locator('.artwork-credits li')).toHaveCount(120);
  await expect(page.getByRole('link', { name: 'Kakashi Hatake — source catalog', exact: true })).toHaveAttribute('href', /myanimelist.net\/character\/85\//);
});

test('character avatar persists and CPU showdown replay cannot award twice', async ({ page }, info) => {
  await page.goto('/signup');
  await page.getByLabel('Username', { exact: true }).fill(`Portrait${Date.now().toString().slice(-8)}${info.project.name.slice(-3)}`);
  await page.getByLabel('Password', { exact: true }).fill('showcase secure password 2026');
  await page.getByLabel('Confirm password', { exact: true }).fill('showcase secure password 2026');
  await page.getByRole('button', { name: 'Create my profile', exact: true }).click();
  await expect(page).toHaveURL(/profile/);
  await page.getByRole('searchbox', { name: 'Find an avatar' }).fill('Naruto');
  await page.locator('.avatar-option').filter({ has: page.locator('input[value="naruto-uzumaki"]') }).click();
  await page.getByRole('button', { name: 'Save avatar', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Avatar saved.' })).toBeVisible();
  await page.reload();
  await expect(page.locator('.player-avatar img')).toHaveAttribute('src', '/characters/naruto-uzumaki.webp');
  await page.goto('/battle');
  await page.getByRole('combobox', { name: 'Opponent', exact: true }).selectOption('cpu');
  await page.getByRole('button', { name: 'Create match', exact: true }).click();
  for (let n = 1; n <= 5; n++) await page.getByRole('button', { name: `Reveal fighter ${n}`, exact: true }).click();
  await page.getByRole('button', { name: 'Keep team', exact: true }).click();
  await page.getByRole('button', { name: 'Lock lineup', exact: true }).click();
  await expect(page.locator('.arena-rounds')).toContainText('ROUND 1 / 5');
  await page.getByRole('button', { name: 'Next round', exact: true }).click();
  await expect(page.locator('.arena-rounds')).toContainText('ROUND 2 / 5');
  await page.getByRole('button', { name: 'Skip to results', exact: true }).click();
  const before = await page.evaluate(async () => (await (await fetch('/api/index?route=auth%2Fme')).json()).data.coins);
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download result card', exact: true }).click();
  const download = await downloadEvent; expect(download.suggestedFilename()).toBe('www-of-anime-result.png');
  await download.saveAs(info.outputPath('result-card.png'));
  await page.getByRole('button', { name: 'Replay showdown', exact: true }).click();
  await expect(page.locator('.arena-rounds')).toContainText('REPLAY');
  await page.getByRole('button', { name: 'Skip to results', exact: true }).click();
  const after = await page.evaluate(async () => (await (await fetch('/api/index?route=auth%2Fme')).json()).data.coins);
  expect(after).toEqual(before);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
